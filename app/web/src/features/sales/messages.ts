export const commerceMessages = { en, ru, uk };
export function useCommerce() {
  const { locale } = useI18n();
  return { c: commerceMessages[locale], locale };
}
export function commerceError(code: string, c: CommerceMessages) {
  return (
    (
      {
        SALE_UNAVAILABLE: c.unavailable,
        SALE_NOT_FOUND: c.unavailable,
        SOLD_OUT: c.soldOut,
        ALREADY_PURCHASED: c.alreadyPurchased,
        INVALID_PRICE: c.invalidPrice,
        INVALID_QUANTITY: c.invalidQuantity,
        INVALID_FIELD: c.invalid,
        INVALID_DATES: c.invalid,
        INVALID_URL: c.invalid,
        SALE_CONFLICT: c.conflict,
        VERSION_REQUIRED: c.conflict,
        PAYMENT_PROCESSING: c.paymentPending,
        CHECKOUT_ENDED: c.checkoutEnded,
        ACCESS_DENIED: c.accessDenied,
        UNAUTHORIZED: c.accessDenied,
      } as Record<string, string>
    )[code] || c.error
  );
}
